#include "libft.h"

t_list	*ft_lstmap(t_list *lst, void *(*f)(void *), void (*del)(void *))
{
	t_list	*newlst;
	t_list	*new;
	void	*content;

	if (!lst || !f || !del)
		return (NULL);
	newlst = NULL;
	while (lst)
	{
		content = f(lst->content);
		new = ft_lstnew(content);
		if (!new)
		{
			del(content);
			ft_lstclear(&newlst, del);
			return (NULL);
		}
		if (!newlst)
			newlst = new;
		else
			ft_lstadd_back(&newlst, new);
		lst = lst->next;
	}
	return (newlst);
}
